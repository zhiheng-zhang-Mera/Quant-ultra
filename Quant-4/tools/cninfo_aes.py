_RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]


def _xtime(a: int) -> int:
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else (a << 1) & 0xFF


def _mul(a: int, b: int) -> int:
    res = 0
    for _ in range(8):
        if b & 1:
            res ^= a
        b >>= 1
        a = _xtime(a)
    return res & 0xFF


def _key_expansion(key: bytes) -> list:
    nk, nr = 4, 10
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (nr + 1)):
        temp = list(w[i - 1])
        if i % nk == 0:
            temp = temp[1:] + temp[:1]
            temp = [_SBOX[b] for b in temp]
            temp[0] ^= _RCON[i // nk - 1]
        w.append([w[i - nk][j] ^ temp[j] for j in range(4)])
    return w


def _add_round_key(state: list, w: list, rnd: int) -> None:
    for c in range(4):
        for r in range(4):
            state[r][c] ^= w[rnd * 4 + c][r]


def _sub_bytes(state: list) -> None:
    for r in range(4):
        for c in range(4):
            state[r][c] = _SBOX[state[r][c]]


def _shift_rows(state: list) -> None:
    for r in range(1, 4):
        state[r] = state[r][r:] + state[r][:r]


def _mix_columns(state: list) -> None:
    for c in range(4):
        a = [state[r][c] for r in range(4)]
        state[0][c] = _mul(a[0], 2) ^ _mul(a[1], 3) ^ a[2] ^ a[3]
        state[1][c] = a[0] ^ _mul(a[1], 2) ^ _mul(a[2], 3) ^ a[3]
        state[2][c] = a[0] ^ a[1] ^ _mul(a[2], 2) ^ _mul(a[3], 3)
        state[3][c] = _mul(a[0], 3) ^ a[1] ^ a[2] ^ _mul(a[3], 2)


def _aes_block(block: bytes, key: bytes) -> bytes:
    # state[r][c] = byte at row r, column c = block[4*c + r] (FIPS-197 layout)
    state = [[block[4 * c + r] for c in range(4)] for r in range(4)]
    w = _key_expansion(key)
    _add_round_key(state, w, 0)
    for rnd in range(1, 10):
        _sub_bytes(state)
        _shift_rows(state)
        _mix_columns(state)
        _add_round_key(state, w, rnd)
    _sub_bytes(state)
    _shift_rows(state)
    _add_round_key(state, w, 10)
    out = bytearray()
    for c in range(4):
        for r in range(4):
            out.append(state[r][c])
    return bytes(out)


def aes_cbc_encrypt_pkcs7(plain: bytes, key: bytes, iv: bytes) -> bytes:
    pad_len = 16 - len(plain) % 16
    plain = plain + bytes([pad_len]) * pad_len
    out = bytearray()
    prev = iv
    for i in range(0, len(plain), 16):
        block = bytes(a ^ b for a, b in zip(plain[i:i + 16], prev))
        enc = _aes_block(block, key)
        out += enc
        prev = enc
    return bytes(out)


def cninfo_mcode(timestamp: int | None = None) -> str:
    """Base64(AES-128-CBC(ts_seconds, key=iv='1234567887654321'))."""
    if timestamp is None:
        timestamp = int(time.time())
    key = iv = b"1234567887654321"
    ct = aes_cbc_encrypt_pkcs7(str(timestamp).encode(), key, iv)
    return base64.b64encode(ct).decode()


